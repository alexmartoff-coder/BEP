from typing import Dict, List

class PromptGenerator:
    def __init__(self, analysis: Dict):
        self.analysis = analysis

    def generate(self) -> str:
        """Генерирует промпт с полным списком серий"""
        series_list = '\n'.join([f"  - {s}" for s in self.analysis['series']])

        prompt = f"""Ты — инженер-сметчик по электротехническому оборудованию CHINT.

Проанализируй электрическую схему и найди ВСЕ автоматические выключатели и защитные аппараты.

Доступные серии из прайс-листа:
{series_list}

Для каждого найденного автомата определи:
1. Обозначение на схеме (QF1, QF2, ...)
2. **ТОЧНУЮ СЕРИЮ** из списка выше (например, NM8N-1600Q EN 3P)
3. Номинальный ток (125А, 63А, 16А)
4. Количество полюсов (1P, 3P, 4P)
5. Тип расцепителя (если виден)

ВАЖНО:
1. Используй ТОЛЬКО серии из списка выше
2. Если серия не определена точно, укажи наиболее вероятную
3. Отвечай ТОЛЬКО в формате JSON массива

Формат: [
  {{"mark":"QF1","series":"NM8N-250S EN 3P","nominal":"125A","poles":"3P"}},
  {{"mark":"QF2","series":"NM8N-250S EN 3P","nominal":"125A","poles":"3P"}}
]"""
        return prompt
